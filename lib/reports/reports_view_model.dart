/// Read-only statement and day-review controller. Temporary review checkboxes
/// never enter account data or create a closing, lock, or financial record.
final class ReportsViewModel extends ChangeNotifier {
  ReportsViewModel(
    this.repository, {
    required this.compareText,
    this.readAccount,
    this.updates,
  }) {
    updates?.addListener(_accountChanged);
  }
  final AccountsRepository repository;
  final int Function(String, String) compareText;
  final AccountDocument Function()? readAccount;
  final Listenable? updates;
  AccountDocument get account =>
      readAccount?.call() ??
      repository.document ??
      (throw StateError('Open an account first.'));
  void _accountChanged() {
    _reviewed.clear();
    _page = 0;
    notifyListeners();
  }

  @override
  void dispose() {
    updates?.removeListener(_accountChanged);
    super.dispose();
  }

  String _from = '', _to = '', _categoryId = '';
  SpendingSource _source = SpendingSource.all;
  int _page = 0;
  static const pageSize = 25;
  final Set<String> _reviewed = {};
  String get from => _from;
  String get to => _to;
  String get categoryId => _categoryId;
  SpendingSource get source => _source;
  int get page => _page;
  Set<String> get reviewedSteps => Set.unmodifiable(_reviewed);
  DailyCashQueries get _queries => DailyCashQueries(account);
  PaidSpendingStatement get statement => _queries.statement(
    from: _from,
    to: _to,
    categoryId: _categoryId,
    source: _source,
  );
  int get pageCount =>
      (statement.rows.length / pageSize).ceil().clamp(1, 1 << 30);
  List<Map<String, Object?>> get pageRows {
    final rows = statement.rows.reversed.toList();
    final effective = _page.clamp(
      0,
      (rows.length / pageSize).ceil().clamp(1, 1 << 30) - 1,
    );
    return List.unmodifiable(rows.skip(effective * pageSize).take(pageSize));
  }

  List<MapEntry<String, BigInt>> get rankedCategories {
    final indexed = statement.byCategory.entries.indexed.toList();
    indexed.sort((a, b) {
      final amount = b.$2.value.compareTo(a.$2.value);
      return amount != 0 ? amount : a.$1.compareTo(b.$1);
    });
    return List.unmodifiable(indexed.map((e) => e.$2));
  }

  CapabilityResult<void> setFilter({
    String from = '',
    String to = '',
    String categoryId = '',
    SpendingSource source = SpendingSource.all,
  }) {
    try {
      _queries.statement(
        from: from,
        to: to,
        categoryId: categoryId,
        source: source,
      );
      _from = from;
      _to = to;
      _categoryId = categoryId;
      _source = source;
      _page = 0;
      notifyListeners();
      return const CapabilitySuccess(null);
    } on FormatException {
      return const CapabilityFailure(
        'invalid_filter',
        'Invalid statement period.',
      );
    } on DomainValidationException {
      return const CapabilityFailure(
        'invalid_filter',
        'Invalid statement period.',
      );
    }
  }

  void setPage(int page) {
    _page = page.clamp(0, pageCount - 1);
    notifyListeners();
  }

  CapabilityResult<void> showToday(String today) => setFilter(
    from: today,
    to: today,
    categoryId: _categoryId,
    source: _source,
  );
  CapabilityResult<void> showMonthToDate(String today) => setFilter(
    from: today.length == 10 ? '${today.substring(0, 8)}01' : today,
    to: today,
    categoryId: _categoryId,
    source: _source,
  );
  CapabilityResult<void> showAll() => setFilter();
  DailyCashSnapshot reviewDay(String date) => _queries.day(date);
  void setReviewed(String step, bool checked) {
    if (checked) {
      _reviewed.add(step);
    } else {
      _reviewed.remove(step);
    }
    notifyListeners();
  }

  void resetReview() {
    _reviewed.clear();
    notifyListeners();
  }

  RestaurantReportComposer get composer =>
      RestaurantReportComposer(account, compareText: compareText);
  RestaurantReport statementReport() => composer.statement(
    from: _from,
    to: _to,
    categoryId: _categoryId,
    source: _source,
  );
}

/// Retains exact generated bytes and report identity for retryable native
/// handoffs; it has no write access to the account repository.
final class ReportDeliveryController extends ChangeNotifier {
  ReportDeliveryController({RestaurantReportPdf? pdf})
    : _pdf = pdf ?? RestaurantReportPdf();
  final RestaurantReportPdf _pdf;
  RestaurantReport? _report;
  Uint8List? _bytes;
  bool _busy = false, _disposed = false;
  bool get isBusy => _busy;
  RestaurantReport? get report => _report;
  Uint8List? get bytes => _bytes == null ? null : Uint8List.fromList(_bytes!);
  @override
  void dispose() {
    _disposed = true;
    super.dispose();
  }

  void _changed() {
    if (!_disposed) {
      notifyListeners();
    }
  }

  Future<CapabilityResult<void>> generate(RestaurantReport report) async {
    if (_disposed || _busy) {
      return const CapabilityFailure('busy', 'Report unavailable.');
    }
    _busy = true;
    _report = null;
    _bytes = null;
    _changed();
    try {
      final result = await _pdf.generate(report);
      if (_disposed) {
        return const CapabilityFailure('disposed', 'Report closed.');
      }
      if (result case CapabilitySuccess<Uint8List>(:final value)) {
        _report = report;
        _bytes = Uint8List.fromList(value);
        return const CapabilitySuccess(null);
      }
      if (result case CapabilityFailure<Uint8List>(
        :final code,
        :final message,
      )) {
        return CapabilityFailure(code, message);
      }
      return const CapabilityCancelled();
    } finally {
      _busy = false;
      _changed();
    }
  }

  Future<CapabilityResult<void>> _deliver(
    Future<CapabilityResult<void>> Function(RestaurantReport, Uint8List) action,
  ) async {
    final report = _report, bytes = _bytes;
    if (_disposed || _busy) {
      return const CapabilityFailure('busy', 'Report unavailable.');
    }
    if (report == null || bytes == null) {
      return const CapabilityFailure('no_report', 'Generate a report first.');
    }
    _busy = true;
    _changed();
    try {
      return await action(report, Uint8List.fromList(bytes));
    } finally {
      _busy = false;
      _changed();
    }
  }

  Future<CapabilityResult<void>> save() => _deliver(_pdf.save);
  Future<CapabilityResult<void>> share() => _deliver(_pdf.share);
  Future<CapabilityResult<void>> print() => _deliver(_pdf.print);
}
